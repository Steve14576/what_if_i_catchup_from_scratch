miss, multi, done = [], [], 0
cache = {}
for f, old, new in R:
    if f not in cache:
        cache[f] = io.open(f, encoding='utf-8').read()
    s = cache[f]
    c = s.count(old)
    if c == 0:
        miss.append((f, old[:50]))
    elif c > 1:
        multi.append((f, old[:50], c))
    else:
        cache[f] = s.replace(old, new)
        done += 1
for f, s in cache.items():
    io.open(f, 'w', encoding='utf-8', newline='\n').write(s)
