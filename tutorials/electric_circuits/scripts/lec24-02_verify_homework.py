import numpy as np

print("=== Q2/Q3：主例的 T 与 H 参数（Z = [[15,5],[5,15]]） ===")
Z = np.array([[15.0, 5.0], [5.0, 15.0]])
A, B, C, D = Z[0, 0] / Z[1, 0], np.linalg.det(Z) / Z[1, 0], 1 / Z[1, 0], Z[1, 1] / Z[1, 0]
print("  T = [[%.0f,%.0f],[%.1f,%.0f]]；AD-BC = %.0f（互易）；A=D=%.0f（对称）" % (A, B, C, D, A * D - B * C, A))
h11, h12, h21, h22 = np.linalg.det(Z) / Z[1, 1], Z[0, 1] / Z[1, 1], -Z[1, 0] / Z[1, 1], 1 / Z[1, 1]
print("  H = [[%.4f,%.4f],[%.4f,%.4f]]；h12 = -h21 = %.4f" % (h11, h12, h21, h22, h12))

print()
print("=== Q4：T 参数的互易/对称判定 ===")
for name, T in [("① [[2,10],[0.1,2]]", np.array([[2.0, 10.0], [0.1, 2.0]])),
                ("② [[3,40],[0.2,3]]", np.array([[3.0, 40.0], [0.2, 3.0]]))]:
    det = T[0, 0] * T[1, 1] - T[0, 1] * T[1, 0]
    reciprocal = abs(det - 1) < 1e-12
    r = "互易" if reciprocal else "非互易"
    # 对称必须蕴含互易：A=D 且 AD-BC=1
    s = "且对称" if (reciprocal and abs(T[0, 0] - T[1, 1]) < 1e-12) else "（不对称）"
    print("  %s：AD-BC = %.1f、A = %.1f、D = %.1f -> %s%s" % (name, det, T[0, 0], T[1, 1], r, s))

print()
print("=== Q5：级联（T^2）与输入阻抗（R_L = 20） ===")
T2 = np.array([[3.0, 40.0], [0.2, 3.0]]) @ np.array([[3.0, 40.0], [0.2, 3.0]])
Zin = (T2[0, 0] * 20 + T2[0, 1]) / (T2[1, 0] * 20 + T2[1, 1])
print("  T^2 = [[%.0f,%.0f],[%.1f,%.0f]]；Z_in = %.4f 欧" % (T2[0, 0], T2[0, 1], T2[1, 0], T2[1, 1], Zin))

print()
print("=== Q6：串联（Z 相加）与并联（Y 相加） ===")
ZA, ZB = np.array([[10.0, 2.0], [2.0, 10.0]]), np.array([[5.0, 1.0], [1.0, 5.0]])
print("  串联：Z = Z_A + Z_B = [[%.0f,%.0f],[%.0f,%.0f]]" % tuple((ZA + ZB).flatten()))
YA, YB = np.linalg.inv(ZA), np.linalg.inv(ZB)
Yp = YA + YB
print("  并联：Y = Y_A + Y_B = [[%.4f,%.4f],[%.4f,%.4f]]" % (Yp[0, 0], Yp[0, 1], Yp[1, 0], Yp[1, 1]))

print()
print("=== Q7：等效电路回读 ===")
Zx = np.array([[20.0, 10.0], [10.0, 20.0]])
print("  T 型（由 Z）：Z11-Z12 = %.0f、Z12 = %.0f、Z22-Z12 = %.0f" % (Zx[0, 0] - Zx[0, 1], Zx[0, 1], Zx[1, 1] - Zx[0, 1]))
Yy = np.array([[0.15, -0.05], [-0.05, 0.15]])
print("  Π 型（由 Y）：Y11+Y12 = %.2f S（%.0f 欧）、-Y12 = %.2f S（%.0f 欧）、Y22+Y12 = %.2f S（%.0f 欧）"
      % (Yy[0, 0] + Yy[0, 1], 1 / (Yy[0, 0] + Yy[0, 1]), -Yy[0, 1], 1 / (-Yy[0, 1]),
         Yy[1, 1] + Yy[0, 1], 1 / (Yy[1, 1] + Yy[0, 1])))

print()
print("=== Q8：综合——两级级联（不同网络）与输入阻抗 ===")
T1 = np.array([[3.0, 40.0], [0.2, 3.0]])
T2b = np.array([[2.0, 30.0], [0.1, 2.0]])
Tt = T1 @ T2b
print("  T = T1*T2 = [[%.0f,%.0f],[%.1f,%.0f]]；AD-BC = %.0f（互易保持）"
      % (Tt[0, 0], Tt[0, 1], Tt[1, 0], Tt[1, 1], Tt[0, 0] * Tt[1, 1] - Tt[0, 1] * Tt[1, 0]))
Zin8 = (Tt[0, 0] * 20 + Tt[0, 1]) / (Tt[1, 0] * 20 + Tt[1, 1])
print("  R_L = 20 时 Z_in = %.4f 欧" % Zin8)

