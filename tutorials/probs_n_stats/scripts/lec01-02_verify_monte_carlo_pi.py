# lec01-02 蒙特卡洛估 pi（第 01 讲 §5.3 几何概型）
# 规模纪律：总耗时 < 3 秒（最大 N=10^6 次投点，numpy 向量化，秒级）。
# 方法：在单位正方形 [0,1]^2 里随机投点，落在四分之一圆 x^2+y^2<=1
#       内的比例 ~ 圆面积/正方形面积 = (pi/4)/1 = pi/4，故 pi ~ 比例*4。
# 几何视角：P(落在圆内) = 面积比 = pi/4，反过来用频率估 pi。
# 输出用 GBK 安全字符（无 ✓ 无 ² 无 →，用 [OK] / ^2 / ->）。
# =====================================================================
import numpy as np

rng = np.random.default_rng(seed=31415926)


def estimate_pi(N):
    """投 N 个点，用圆内比例*4 估 pi。"""
    x = rng.uniform(0.0, 1.0, size=N)
    y = rng.uniform(0.0, 1.0, size=N)
    inside = np.sum(x * x + y * y <= 1.0)
    return 4.0 * inside / N


PI_TRUE = 3.141592653589793

print("实验：单位正方形内随机投点，用'圆内比例 x 4'估 pi")
print("  理论：P(点在圆内) = 圆面积/正方形面积 = (pi/4)/1，即 pi = 4 x P")
for N in [1_000, 10_000, 100_000, 1_000_000]:
    est = estimate_pi(N)
    print("    N=%7d  估pi=%.6f  误差=%.6f  比例实=%.6f(理论 pi/4=%.6f)"
          % (N, est, abs(est - PI_TRUE), est / 4, PI_TRUE / 4))
print("-> 结论 1：几何概型 P(A)=面积比 = pi/4 ≈ 0.7854，模拟坐实。")
print("-> 结论 2：把等式反过来用，频率 x 4 就能估出 pi；N 越大越接近。")
print("-> 结论 3：误差下降速率大约 1/sqrt(N)（第 14 讲 CLT 会解释为什么）。")
print("[OK] 蒙特卡洛实验完成。")