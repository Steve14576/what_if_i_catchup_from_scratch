# lec06-01 均匀分布的密度、归一化与"密度可大于 1"（第 06 讲 §1 / §2）
# 规模纪律：数值积分 + 20 万次模拟，目标 < 5 秒。
#   U(a,b)：f(x)=1/(b-a)（a<x<b），F(x)=(x-a)/(b-a)
#   关键演示：U(0,0.5) 的密度 = 2 > 1，但它仍是合法密度。
# 输出用 GBK 安全字符（-> / [OK]）。
# =====================================================================
import numpy as np

rng = np.random.default_rng(seed=20261031)


def trapz(y, x):
    """手写梯形积分，避免不同 numpy 版本 np.trapz/np.trapezoid 的差异。"""
    return float(np.sum((y[1:] + y[:-1]) / 2 * np.diff(x)))


print("=== 实验 1：U(2,5) 的密度归一化 ===")
a, b = 2.0, 5.0
x = np.linspace(a, b, 200001)
f = np.full_like(x, 1 / (b - a))
print("  密度 f(x) = 1/(b-a) = %.6f" % (1 / (b - a)))
print("  数值积分 = %.6f（理论 1）" % trapz(f, x))

trials = 200000
u = rng.uniform(a, b, trials)
print("=== 实验 2：区间概率 = 密度曲线下的面积 ===")
print("  P(3<X<4) = 面积 = %.4f（理论 (4-3)/(5-2)）" % ((4 - 3) / (b - a)))
print("  模拟 P(3<X<4) = %.4f" % np.mean((u > 3) & (u < 4)))

print("=== 实验 3：密度可以大于 1 ===")
a2, b2 = 0.0, 0.5
f2 = 1 / (b2 - a2)
print("  U(0,0.5) 的密度 f(x) = %.1f（大于 1）" % f2)
print("  但总积分 = %.1f x %.1f = %.1f，仍合法" % (f2, b2 - a2, f2 * (b2 - a2)))
u2 = rng.uniform(a2, b2, trials)
print("  P(0<X<0.25) = %.4f（理论 0.5000）" % np.mean((u2 > 0) & (u2 < 0.25)))
print("  单点 P(X=0.25) 的模拟频率 = %.4f（理论 0，几乎取不到精确单点）" % np.mean(u2 == 0.25))
print("-> 结论：密度是'单位长度上的概率'，数值可以大于 1；概率是密度在区间上的积分。")
print("[OK] 均匀分布验证完成。")