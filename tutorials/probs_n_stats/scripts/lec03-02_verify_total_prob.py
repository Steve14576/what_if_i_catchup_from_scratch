# =====================================================================
# lec03-02 全概率公式验证：两工厂次品（第 03 讲 §4）
# 规模纪律：精确 + 100 万次模拟，目标 < 5 秒。
# 工厂甲供 60% 产品、次品率 2%；工厂乙供 40%、次品率 5%。
#   全概率：P(次品) = P(甲)P(次品|甲) + P(乙)P(次品|乙)
# 输出用 GBK 安全字符（-> / [OK]）。
# =====================================================================
import numpy as np

rng = np.random.default_rng(seed=20261018)
p_a, d_a = 0.60, 0.02     # 甲：占比、次品率
p_b, d_b = 0.40, 0.05     # 乙：占比、次品率

total = p_a * d_a + p_b * d_b
print("=== 全概率：P(次品) = P(甲)P(次品|甲) + P(乙)P(次品|乙) ===")
print("  = %.2f*%.2f + %.2f*%.2f = %.4f + %.4f = %.4f"
      % (p_a, d_a, p_b, d_b, p_a * d_a, p_b * d_b, total))

trials = 1_000_000
from_a = rng.random(trials) < p_a           # True -> 来自甲厂
rate = np.where(from_a, d_a, d_b)
defect = rng.random(trials) < rate
print("  模拟 %d 件产品，次品频率 = %.4f" % (trials, defect.mean()))
print("-> 结论：全概率公式把'按来源分块、各自加权'的加权平均写成加法，理论与模拟一致。")
print("[OK] 全概率公式验证完成。")