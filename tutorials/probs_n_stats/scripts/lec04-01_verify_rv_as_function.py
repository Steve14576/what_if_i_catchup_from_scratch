# lec04-01 同一个样本空间上的不同随机变量（第 04 讲 §1）
# 规模纪律：穷举 36 个结果，目标 < 3 秒。
# 掷两枚骰子的样本空间（36 个有序对）上，定义三个不同的随机变量：
#   X1 = 点数之和, X2 = 两枚中的最大值, X3 = 两枚点数之差（绝对值）
# 各自得到不同的分布律——说明"随机变量是你要选的那个函数"。
# 输出用 GBK 安全字符（-> / [OK]）。
# =====================================================================
out = [(a, b) for a in range(1, 7) for b in range(1, 7)]
N = len(out)


def pmf(f):
    d = {}
    for o in out:
        v = f(o)
        d[v] = d.get(v, 0) + 1
    return {k: v / N for k, v in sorted(d.items())}


cases = [
    ("X1 = 和", lambda o: o[0] + o[1]),
    ("X2 = 最大值", lambda o: max(o)),
    ("X3 = 点数之差", lambda o: abs(o[0] - o[1])),
]
for name, f in cases:
    d = pmf(f)
    print("随机变量 %s 的分布律：" % name)
    for k, v in d.items():
        print("    X=%2d  概率=%.4f（记 %d/36）" % (k, v, round(v * N)))
    print("    概率总和 = %.4f" % sum(d.values()))
print("-> 结论：同一个试验、同一个样本空间，选不同的随机变量就得到不同的分布律；随机变量是人选的函数。")
print("[OK] 三个随机变量的分布律枚举完成。")