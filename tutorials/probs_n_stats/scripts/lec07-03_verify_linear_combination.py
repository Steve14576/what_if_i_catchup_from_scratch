# lec07-03 正态分布的线性不变性（第 07 讲 §6）
# 规模纪律：100 万次模拟，目标 < 5 秒。
# 方法：
#   1) 单个线性变换：X~N(5, 2^2)，Y=3X-1，理论 Y~N(14, 6^2)。
#   2) 两个独立正态之和：X1~N(5,4)、X2~N(3,9)，理论和~N(8,13)。
#   3) 用分位数对照形状（不只比均值方差），确认"还是正态"。
# 输出用 GBK 安全字符（无 ✓ 无 ² 无 →，用 [OK] / ^2 / ->）。
# =====================================================================
import math
import numpy as np

rng = np.random.default_rng(seed=20261101)
n = 1000000


def phi(z):
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


print("=== 实验 1：Y = 3X - 1，X~N(5, 2^2) ===")
x = rng.normal(5.0, 2.0, n)
y = 3 * x - 1
print("  Y 模拟均值=%.4f  模拟标准差=%.4f（理论 14 / 6）"
      % (np.mean(y), np.std(y)))
print("  P(Y<=20): 模拟=%.4f  理论=%.4f（z=(20-14)/6=1）"
      % (np.mean(y <= 20), phi(1.0)))
for q in [0.025, 0.5, 0.975]:
    zq = {0.025: -1.96, 0.5: 0.0, 0.975: 1.96}[q]
    print("    分位点 %.3f：模拟=%.4f  理论=%.4f"
          % (q, np.quantile(y, q), 14 + 6 * zq))
print("  -> 结论：aX+b 仍是正态，均值变 a*mu+b，标准差变 |a|*sigma。")

print("=== 实验 2：两个独立正态之和 ===")
x1 = rng.normal(5.0, 2.0, n)     # N(5, 4)
x2 = rng.normal(3.0, 3.0, n)     # N(3, 9)
s = x1 + x2
print("  和 模拟均值=%.4f  模拟标准差=%.4f（理论 8 / sqrt(13)=%.4f）"
      % (np.mean(s), np.std(s), math.sqrt(13)))
print("  P(和<=10): 模拟=%.4f  理论=%.4f（z=(10-8)/sqrt(13)=%.4f）"
      % (np.mean(s <= 10), phi(2 / math.sqrt(13)), 2 / math.sqrt(13)))
print("  方差核对：2^2 + 3^2 = %d（不是 (2+3)^2=25）" % (4 + 9))
print("  -> 结论：独立正态相加，均值相加、方差相加；标准差不相加。")

print("=== 实验 3：形状对照（分位点 vs 标准正态） ===")
z = (s - 8) / math.sqrt(13)
for q in [0.05, 0.25, 0.5, 0.75, 0.95]:
    zq = {0.05: -1.645, 0.25: -0.674, 0.5: 0.0, 0.75: 0.674, 0.95: 1.645}[q]
    print("    分位点 %.2f：标准化后=%.4f  标准正态=%.4f"
          % (q, np.quantile(z, q), zq))
print("  -> 结论：不只是均值方差对上，整条分位数曲线都对上，形状仍是正态。")
