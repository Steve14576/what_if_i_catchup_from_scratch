# lec04-03 连续型的分布函数：均匀分布 U(0,1)（第 04 讲 §4）
# 规模纪律：20 万次模拟，目标 < 5 秒。
# 连续均匀分布 U(0,1)：F(x)=x（0<=x<=1），单点概率为 0，区间概率=区间长度。
# 用模拟的经验分布函数（ECDF）对照理论 F(x)=x。
# 输出用 GBK 安全字符（-> / [OK]）。
# =====================================================================
import numpy as np

rng = np.random.default_rng(seed=20261018)
trials = 200000
u = rng.uniform(0.0, 1.0, trials)

print("=== 连续均匀分布 U(0,1)：理论 F(x)=x (0<=x<=1) ===")
for x in [0.2, 0.5, 0.8]:
    emp = np.mean(u <= x)
    print("  x=%.1f  经验 F=%.4f  理论 F=%.4f" % (x, emp, x))

print("=== 连续型的特征 ===")
one_point = np.mean(u == 0.5)
print("  单点概率 P(X=0.5)：模拟频率 = %.4f（理论 0，几乎取不到精确的单点）" % one_point)
seg = np.mean((u > 0.3) & (u <= 0.7))
print("  区间概率 P(0.3<X<=0.7)：模拟 = %.4f  理论 = 0.4（=F(0.7)-F(0.3)=0.7-0.3）" % seg)
print("-> 结论：连续型分布函数是连续曲线；单点概率为 0；区间概率由 F 相减、等于区间长度。")
print("-> 对照：离散型的分布函数是阶梯状（见 lec04-02）。")
print("[OK] 连续型均匀分布验证完成。")